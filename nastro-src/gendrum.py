# exec'd from gen.py: builds drum-voice.pd and drum.pd (DRUM mode: 24-slice sampler)

def osc4(path, types, args):
    return f"\\; oscOut sendtyped /oled/{path} {types} 3 {args}"


NV = 6          # voices
