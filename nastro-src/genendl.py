# exec'd from gen.py: builds endl.pd - ENDLESS sequencer, 4th page of SEQ (AUX+E: TEMPO -> STEP -> TOMBOLA -> ENDLESS)
# Stopped: every key appends a note (max 64), AUX+A# a rest, AUX+B clears. AUX+C5 start / stop.
# Running (clocked by the tape, like STEP): loops for ever; a key transposes it relative to its first note.
# Knobs (ctx 17): 1 RATE 1/4 1/8 1/16 1/32   2 GATE   3 DIRECTION > < <> ?   4 PROB (chance that a step sounds)
# endp: 0 rate idx  1 gate  2 dir idx  3 prob  4 on  5 transpose  6 length  7 position  8 ping-pong direction
# Rules followed here (Pd): [r name] has no inlet; a multi-outlet expr never writes what it reads (writes go
# through pack -> message afterwards); [delay] gets bangs only (its time goes to the right inlet).
MAXN = 64
WIN = 32                     # steps on screen (4 px each)
SC = "\\;"                   # message separator inside Pd message boxes
D1 = "\\$1"


def E(s):
    """natural expression text -> Pd expr text (escaped commas / semicolons)"""
    return s.replace(",", " \\, ").replace(";", " \\; ")


def M(*parts):
    """Pd message box text that sends to several receivers: M('endp 4 0', 'endp 7 -1')"""
    return " ".join(f"{SC} {p}" for p in parts)


def osce(path, types, args):
    return f"{SC} oscOut sendtyped /oled/{path} {types} 3 {args}"


en = Patch(2600, 1800)
en.text(20, 5, "endl: ENDLESS sequencer - stopped: keys append notes (AUX+A# rest - AUX+B clear) - AUX+C5 start/stop - "
               "running: a key transposes. knobs: rate gate direction prob")
en.obj(20, 30, f"table endn {MAXN}")
en.obj(150, 30, "table endp 10")
en.obj(280, 30, "table endw 1")              # first step shown on screen
initM = en.msg(120, 60, M("endn const 0", "endp 0 2 0.5 0 1 0 0 0 -1 1", "endw 0 0"))
en.c(en.obj(20, 60, "loadbang"), initM)
dirty = en.msg(1800, 60, "1")

# ------------------------------------------------ page active: SEQ mode, page 3
actE = en.obj(20, 150, "expr $f1==4 && $f2==3")
mT = en.obj(20, 120, "t f")
en.c(en.obj(20, 100, "r mode"), mT)
en.c(mT, actE, 0, 0)
pgT = en.obj(120, 120, "t b f")
en.c(en.obj(120, 100, "r seq-page"), pgT)
en.c(pgT, actE, 1, 1)
en.c(pgT, actE, 0, 0)
actC = en.obj(20, 180, "change")
en.c(actE, actC)
actT = en.obj(20, 210, "t f f f f")          # 3 screen metro + step spigot, 2 aux gate, 1 key gate, 0 entry redraw
en.c(actC, actT)
entS = en.obj(150, 240, "sel 1")
en.c(actT, entS, 0)
en.c(entS, dirty)

# ------------------------------------------------ knobs
krt = en.obj(500, 90, "route 1 2 3 4")
en.c(en.obj(500, 60, "r endl-knob"), krt)
en.c(en.obj(600, 60, "r endl-set"), krt)
for i, (ex, idx) in enumerate((("expr int($f1*3.99)", 0), ("expr 0.1+$f1*0.9", 1),
                                ("expr int($f1*3.99)", 2), ("expr $f1", 3))):
    e = en.obj(500 + i * 120, 120, ex)
    t = en.obj(500 + i * 120, 150, "t b f")
    en.c(krt, e, i)
    en.c(e, t)
    en.c(t, en.msg(500 + i * 120, 180, M(f"endp {idx} {D1}")), 1)
    en.c(t, dirty, 0)

# ------------------------------------------------ keys: append (stopped) or transpose (running)
nu = en.obj(1000, 90, "unpack f f")
en.c(en.obj(1000, 60, "r notes"), nu)
nOn = en.obj(1080, 120, "> 0")
nSp = en.obj(1000, 150, "spigot")
nSp2 = en.obj(1000, 180, "spigot")
en.c(nu, nOn, 1)
en.c(nOn, nSp, 0, 1)
en.c(nu, nSp, 0)
en.c(nSp, nSp2)
en.c(actT, nSp2, 1, 1)
auxSp = en.obj(1000, 195, "spigot 1")           # keys pressed with AUX held are commands, not notes
auxN = en.obj(1100, 180, "== 0")
en.c(en.obj(1100, 150, "r aux"), auxN)
en.c(auxN, auxSp, 0, 1)
en.c(nSp2, auxSp)
keyT = en.obj(1000, 210, "t f f")
en.c(auxSp, keyT)
runE = en.obj(1100, 240, "expr endp[4]>0")
runN = en.obj(1200, 255, "== 0")
runS = en.obj(1000, 270, "spigot")
stopS = en.obj(1100, 270, "spigot")
en.c(keyT, runE, 1)
en.c(runE, runS, 0, 1)
en.c(runE, runN)
en.c(runN, stopS, 0, 1)
en.c(keyT, runS, 0)
en.c(keyT, stopS, 0)
# append: ok (not full) ; note ; index ; new length  -> pack (ok arrives last) -> route 1 -> message
appIn = en.obj(1100, 300, "t f")
en.c(stopS, appIn)
appE = en.obj(1100, 330, "expr " + E(f"endp[6]<{MAXN}; $f1; endp[6]; endp[6]+1"))
en.c(appIn, appE)
appP = en.obj(1100, 360, "pack f f f f")
for o in range(4):
    en.c(appE, appP, o, o)
appR = en.obj(1100, 390, "route 1")
en.c(appP, appR)
appM = en.msg(1100, 420, M("endn \\$2 \\$1", "endp 6 \\$3"))
en.c(appR, appM)
en.c(appR, dirty)
# transpose while running: key - first note (60 if the first step is a rest)
trE = en.obj(1000, 330, "expr " + E("$f1-if(endn[0]>0, endn[0], 60)"))
en.c(runS, trE)
en.c(trE, en.msg(1000, 360, M(f"endp 5 {D1}")))
# AUX keys (page active): 70 rest (stopped only), 71 clear, 72 start / stop
akSp = en.obj(1500, 90, "spigot")
en.c(en.obj(1500, 60, "r aux-key"), akSp)
en.c(actT, akSp, 2, 1)
aks = en.obj(1500, 120, "sel 70 71 72")
en.c(akSp, aks)
restE = en.obj(1500, 150, "expr endp[4]==0")
restS = en.obj(1500, 180, "sel 1")
rest0 = en.msg(1500, 210, "0")
en.c(aks, restE, 0)
en.c(restE, restS)
en.c(restS, rest0)
en.c(rest0, appIn)
clrM = en.msg(1600, 150, M("endn const 0", "endp 6 0", "endp 7 -1", "endp 5 0", "endw 0 0"))
en.c(aks, clrM, 1)
en.c(clrM, dirty)
onE = en.obj(1700, 150, "expr endp[4]==0")
onT = en.obj(1700, 180, "t b f")
en.c(aks, onE, 2)
en.c(onE, onT)
en.c(onT, en.msg(1700, 210, M(f"endp 4 {D1}", "endp 7 -1", "endp 8 1", "endp 5 0")), 1)
en.c(onT, dirty, 0)

# ------------------------------------------------ clock (tape 16ths) -> steps
bmF = en.obj(400, 600, "f 500")
en.c(en.obj(400, 570, "r tempo-beatms"), bmF, 0, 1)
fireE = en.obj(20, 630, "expr " + E("endp[4]>0 && endp[6]>0 && ($f1 % if(endp[0]==0, 4, if(endp[0]==1, 2, 1)))==0"))
en.c(en.obj(20, 600, "r tick16"), fireE)
fireS = en.obj(20, 660, "sel 1")
en.c(fireE, fireS)
fireT = en.obj(20, 690, "t b b")                 # 1: extra half step for 1/32, 0: step now
en.c(fireS, fireT)
step = en.obj(20, 760, "t b b b b")              # 3 gate time, 2 next position, 1 play, 0 playhead on screen
en.c(fireT, step, 0)
halfE = en.obj(200, 690, "expr endp[0]==3")
halfS = en.obj(200, 720, "sel 1")
halfD = en.obj(200, 750, "delay")
halfMs = en.obj(300, 720, "/ 8")
halfB = en.obj(300, 690, "t b")
en.c(fireT, halfB, 1)
en.c(halfB, bmF)
en.c(bmF, halfMs)
en.c(halfMs, halfD, 0, 1)                        # delay time (right inlet)
en.c(fireT, halfE, 1)
en.c(halfE, halfS)
en.c(halfS, halfD)
en.c(halfD, step)
# gate time (ms) = 16th * 16ths-per-step * gate -> pipe delay
gateB = en.obj(400, 790, "t b")
en.c(step, gateB, 3)
gateF = en.obj(500, 790, "f 500")
en.c(en.obj(500, 760, "r tempo-beatms"), gateF, 0, 1)
en.c(gateB, gateF)
gateE = en.obj(400, 820, "expr " + E("$f1/4*if(endp[0]==0, 4, if(endp[0]==1, 2, if(endp[0]==2, 1, 0.5)))*endp[1]"))
en.c(gateF, gateE)
# next position: outlet 0 position, 1 ping-pong direction (reads endp only, written afterwards by a message)
P, L, Dr, Q = "endp[7]", "endp[6]", "endp[2]", "endp[8]"
PP = f"if({L}<2, 0, if({P}<0, 0, if({P}+{Q}>={L}, {L}-2, if({P}+{Q}<0, 1, {P}+{Q}))))"
NP = (f"if({Dr}==0, if({P}<0, 0, ({P}+1)%{L}), if({Dr}==1, if({P}<0, {L}-1, ({P}-1+{L})%{L}), "
      f"if({Dr}==2, {PP}, $f2%{L})))")
NQ = f"if({P}<0, 1, if({P}+{Q}>={L}, -1, if({P}+{Q}<0, 1, {Q})))"
posT = en.obj(20, 820, "t b b")
en.c(step, posT, 2)
rnd = en.obj(120, 850, f"random {MAXN * 16}")
posE = en.obj(20, 880, "expr " + E(f"0*$f1+{NP}; {NQ}"))
en.c(posT, rnd, 1)
en.c(rnd, posE, 0, 1)
en.c(posT, posE, 0)
posP = en.obj(20, 910, "pack f f")
en.c(posE, posP, 1, 1)
en.c(posE, posP, 0, 0)
en.c(posP, en.msg(20, 940, M(f"endp 7 {D1}", "endp 8 \\$2")))
# play the step: ok (a note, and the chance) ; note + transpose
plT = en.obj(600, 820, "t b b")
en.c(step, plT, 1)
plR = en.obj(700, 850, "random 100")
plE = en.obj(600, 880, "expr " + E("0*$f1+(endn[endp[7]]>0 && $f2<endp[3]*100); endn[endp[7]]+endp[5]"))
en.c(plT, plR, 1)
en.c(plR, plE, 0, 1)
en.c(plT, plE, 0)
plP = en.obj(600, 910, "pack f f")
en.c(plE, plP, 1, 1)
en.c(plE, plP, 0, 0)
plRt = en.obj(600, 940, "route 1")
en.c(plP, plRt)
noteT = en.obj(600, 970, "t f f")
en.c(plRt, noteT)
sn = en.obj(600, 1090, "s seq-notes")
onM = en.msg(700, 1000, f"{D1} 100")
en.c(noteT, onM, 1)
en.c(onM, sn)
offP = en.obj(600, 1000, "pipe 100")
en.c(gateE, offP, 0, 1)
en.c(noteT, offP, 0)
offM = en.msg(600, 1030, f"{D1} 0")
en.c(offP, offM)
en.c(offM, sn)
# start from the first step when the tape starts playing
tpS = en.obj(900, 600, "sel 1")
en.c(en.obj(900, 570, "r tp-play"), tpS)
en.c(tpS, en.msg(900, 630, M("endp 7 -1", "endp 8 1")))

# ------------------------------------------------ save / load with the project
svT = en.obj(1200, 600, "t f f")
en.c(en.obj(1200, 570, "r nst-save"), svT)
mkN = en.obj(1200, 630, "makefilename p%d-endn.txt")
mkP = en.obj(1400, 630, "makefilename p%d-endp.txt")
en.c(svT, mkN, 1)
en.c(svT, mkP, 0)
en.c(mkN, en.msg(1200, 660, M(f"endn write {D1}")))
en.c(mkP, en.msg(1400, 660, M(f"endp write {D1}")))
ldT = en.obj(1600, 600, "t b f b")                # 2 clear, 1 read the files, 0 stopped + redraw
en.c(en.obj(1600, 570, "r nst-load"), ldT)
en.c(ldT, initM, 2)
lkN = en.obj(1600, 630, "makefilename p%d-endn.txt")
lkP = en.obj(1800, 630, "makefilename p%d-endp.txt")
en.c(ldT, lkN, 1)
en.c(ldT, lkP, 1)
en.c(lkN, en.msg(1600, 660, M(f"endn read {D1}")))
en.c(lkP, en.msg(1800, 660, M(f"endp read {D1}")))
en.c(ldT, en.msg(1600, 690, M("endp 4 0", "endp 7 -1", "endp 5 0", "endp 8 1", "endw 0 0")), 0)
en.c(ldT, dirty, 0)

# ------------------------------------------------ screen (page active)
# full redraw when dirty (max 10 fps); on every step only the playhead column moves (2 inverted columns)
dF = en.obj(1800, 120, "f 1")
en.c(dirty, dF, 0, 1)
mtr = en.obj(1900, 90, "metro 100")
en.c(actT, mtr, 3)
en.c(mtr, dF)
dS = en.obj(1800, 150, "sel 1")
en.c(dF, dS)
full = en.obj(1800, 180, "t b b b b b b")       # 5 window, 4 header, 3 steps, 2 bottom, 1 playhead, 0 flip
z = en.msg(1950, 150, "0")
en.c(dS, full)
en.c(dS, z)
en.c(z, dF, 0, 1)
# 5: first step shown: the playhead's page when running, the end of the sequence when recording
winE = en.obj(1800, 210, "expr " + E(f"if(endp[4]>0, int(max(endp[7], 0)/{WIN})*{WIN}, int(max(endp[6]-1, 0)/{WIN})*{WIN})"))
en.c(full, winE, 5)
en.c(winE, en.msg(1800, 240, M(f"endw 0 {D1}")))
# 4: header
hdE = en.obj(2000, 210, "expr " + E("endp[4]; endp[6]"))
en.c(full, hdE, 4)
hdP = en.obj(2000, 240, "pack f f")
en.c(hdE, hdP, 1, 1)
en.c(hdE, hdP, 0, 0)
hdR = en.obj(2000, 270, "route 0 1")
en.c(hdP, hdR)
HEAD = osce("gShowInfoBar", "ii", "0") + " " + osce("gClear", "ii", "1") + " " + osce("gPrintln", "iiiiis", "1 1 8 1 ENDLESS")
en.c(hdR, en.msg(2000, 300, HEAD + " " + osce("gPrintln", "iiiiisf", f"70 1 8 1 REC {D1}")), 0)
en.c(hdR, en.msg(2200, 300, HEAD + " " + osce("gFillArea", "iiiiii", "66 0 62 10 1") + " " +
                 osce("gPrintln", "iiiiisf", f"68 1 8 0 PLAY {D1}")), 1)
# 3: the steps in the window: note = small box (higher note = higher), rest = dash on the base line
stT = en.obj(1800, 330, "t b b b")
en.c(full, stT, 3)
en.c(stT, en.msg(2100, 330, osce("gLine", "iiiiii", "0 52 127 52 1")), 2)
stN = en.msg(1800, 360, str(WIN))
stZ = en.msg(1860, 360, "0")
stU = en.obj(1800, 390, "until")
stC = en.obj(1800, 420, "f")
stC1 = en.obj(1860, 420, "+ 1")
en.c(stT, stZ, 1)
en.c(stZ, stC, 0, 1)
en.c(stT, stN, 0)
en.c(stN, stU)
en.c(stU, stC)
en.c(stC, stC1)
en.c(stC1, stC, 0, 1)
IDX = "endw[0]+$f1"
stE = en.obj(1800, 450, "expr " + E(f"if({IDX}<endp[6], if(endn[{IDX}]>0, 1, 2), 0); $f1*4; "
                                    f"max(11, min(47, 47-int((endn[{IDX}]-36)*0.75)))"))
en.c(stC, stE)
stP = en.obj(1800, 480, "pack f f f")
for o in range(3):
    en.c(stE, stP, o, o)
stR = en.obj(1800, 510, "route 1 2")
en.c(stP, stR)
en.c(stR, en.msg(1800, 540, osce("gFillArea", "iiiiii", f"{D1} \\$2 3 3 1")), 0)
en.c(stR, en.msg(1950, 540, osce("gFillArea", "iiiiii", f"{D1} 49 3 1 1")), 1)
# 2: bottom row: rate, gate, direction, prob
btE = en.obj(2100, 360, "expr " + E("endp[0]; int(endp[1]*100); endp[2]; int(endp[3]*100)"))
en.c(full, btE, 2)
rateS = en.obj(2100, 390, "sel 0 1 2 3")
en.c(btE, rateS, 0)
for i, nm in enumerate(("1/4", "1/8", "1/16", "1/32")):
    en.c(rateS, en.msg(2100 + i * 60, 420, osce("gPrintln", "iiiiis", f"1 55 8 1 {nm}")), i)
en.c(btE, en.msg(2100, 450, osce("gPrintln", "iiiiisf", f"36 55 8 1 G {D1}")), 1)
dirS = en.obj(2300, 390, "sel 0 1 2 3")
en.c(btE, dirS, 2)
for i, nm in enumerate((">>", "<<", "<>", "??")):
    en.c(dirS, en.msg(2300 + i * 60, 420, osce("gPrintln", "iiiiis", f"72 55 8 1 {nm}")), i)
en.c(btE, en.msg(2300, 450, osce("gPrintln", "iiiiisf", f"92 55 8 1 P {D1}")), 3)
# 1: playhead after a full redraw
INV = osce("gInvertArea", "iiiii", f"{D1} 10 4 41")
shownF = en.obj(2400, 600, "f -1")
phE = en.obj(2200, 480, "expr " + E("if(endp[4]>0 && endp[7]>=0, endp[7]-endw[0], -1)"))
en.c(full, phE, 1)
phT = en.obj(2200, 510, "t f f")
en.c(phE, phT)
en.c(phT, shownF, 1, 1)
phM = en.obj(2200, 540, "moses 0")
phX = en.obj(2250, 570, "* 4")
en.c(phT, phM, 0)
en.c(phM, phX, 1)
en.c(phX, en.msg(2250, 600, INV))
en.c(full, en.msg(1800, 600, f"{SC} oscOut sendtyped /oled/gFlip i 3"), 0)
# 0 on each step (page active): outside the window -> full redraw, else move the inverted column
pgSp = en.obj(20, 1100, "spigot")
en.c(actT, pgSp, 3, 1)
en.c(step, pgSp, 0)
colE = en.obj(20, 1130, "expr " + E(f"endp[7]-endw[0]>=0 && endp[7]-endw[0]<{WIN}; endp[7]-endw[0]"))   # in window ; column
en.c(pgSp, colE)
colP = en.obj(20, 1160, "pack f f")
en.c(colE, colP, 1, 1)
en.c(colE, colP, 0, 0)
colR = en.obj(20, 1190, "route 1 0")
en.c(colP, colR)
en.c(colR, dirty, 1)
mvT = en.obj(20, 1220, "t f b")
en.c(colR, mvT, 0)
oldM = en.obj(150, 1250, "moses 0")
oldX = en.obj(200, 1280, "* 4")
en.c(mvT, shownF, 1)
en.c(shownF, oldM)
en.c(oldM, oldX, 1)
en.c(oldX, en.msg(200, 1310, INV))
newT = en.obj(20, 1250, "t f f")
en.c(mvT, newT, 0)
en.c(newT, shownF, 1, 1)
newX = en.obj(20, 1280, "* 4")
en.c(newT, newX, 0)
en.c(newX, en.msg(20, 1310, INV + f" {SC} oscOut sendtyped /oled/gFlip i 3"))
en.save("endl.pd")
