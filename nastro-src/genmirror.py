# exec'd from gen.py: builds mirror.pd - mirrors the OLED (and the LED) to a computer over Wi-Fi, for screen recording.
# Off at start. The projects menu item "SCREEN TO MAC" toggles it ([r nst-mirror-toggle]); the state is published
# on [s nst-mirror-on]. The computer's IP address is read from mirror.txt next to the patch (e.g. "192.168.1.114;").
# Commands go out as UDP FUDI text on port 9123, the format oled-sim.py understands.
# On the computer: OLED_BIND=0.0.0.0 python3 oled-sim.py, then open http://localhost:8123
mi = Patch(900, 600)
mi.text(20, 5, "mirror: copy of the OLED to a computer - menu SCREEN TO MAC toggles it - mirror.txt = its IP address")
mi.obj(20, 30, "text define nst-mirror")
ns = mi.obj(150, 450, "netsend -u")
# toggle
onF = mi.obj(20, 90, "f 0")
tg = mi.obj(20, 120, "== 0")
mi.c(mi.obj(20, 60, "r nst-mirror-toggle"), onF)
mi.c(onF, tg)
tgT = mi.obj(20, 135, "t f f")                      # store the new state first, then act on it
mi.c(tg, tgT)
mi.c(tgT, onF, 1, 1)
tgS = mi.obj(20, 150, "sel 1 0")
mi.c(tgT, tgS, 0)
# on: read the address and connect - or say the file is missing and stay off
onT = mi.obj(20, 180, "t b b")
mi.c(tgS, onT, 0)
mi.c(onT, mi.msg(120, 180, "\\; nst-mirror clear \\; nst-mirror read mirror.txt"), 1)
sz = mi.obj(20, 210, "text size nst-mirror")
mi.c(onT, sz, 0)
has = mi.obj(20, 240, "moses 1")
mi.c(sz, has)
missT = mi.obj(20, 270, "t b b")
mi.c(has, missT, 0)
z0 = mi.msg(120, 300, "0")
mi.c(missT, z0, 1)
mi.c(z0, onF, 0, 1)
mi.c(missT, mi.msg(20, 300, "\\; nst-proj-status symbol NO-MIRROR.TXT \\; nst-mirror-on 0"), 0)
gz = mi.msg(150, 255, "0")
get = mi.obj(150, 280, "text get nst-mirror")
mi.c(has, gz, 1)
mi.c(gz, get)
con = mi.msg(150, 310, "connect \\$1 9123")
mi.c(get, con)
mi.c(con, ns)
# off: disconnect
offT = mi.obj(300, 180, "t b b")
mi.c(tgS, offT, 1)
disc = mi.msg(300, 210, "disconnect")
mi.c(offT, disc, 1)
mi.c(disc, ns)
mi.c(offT, mi.msg(400, 210, "\\; nst-proj-status symbol SCREEN-OFF \\; nst-mirror-on 0"), 0)
# connection status: gate the relay; when connected tell the menu and redraw everything for the computer
ok = mi.obj(300, 480, "spigot")
mi.c(ns, ok, 0, 1)
okS = mi.obj(150, 480, "sel 1")
mi.c(ns, okS)
dl = mi.obj(150, 510, "delay 200")
mi.c(okS, dl)
mi.c(okS, mi.msg(250, 510, "\\; nst-proj-status symbol SCREEN-ON \\; nst-mirror-on 1"))
mi.c(dl, mi.msg(150, 540, "\\; nst-redraw bang"))
# relays: OLED commands and the LED (only while connected)
lp = mi.obj(300, 390, "list prepend send")
lt = mi.obj(300, 420, "list trim")
# VIS frames are heavy: at most one gFrame every 500 ms, no gWaveform (apply_mirrorthrottle.py)
rTy = mi.obj(300, 330, "route sendtyped")
mi.c(mi.obj(300, 300, "r oscOut"), rTy)
mi.c(rTy, lp, 1)                                     # plain commands: as before
rHv = mi.obj(560, 330, "route /oled/gFrame /oled/gWaveform")
mi.c(rTy, rHv, 0)
lpT = mi.obj(760, 360, "list prepend sendtyped")     # other typed commands (gFlip ...): as before
mi.c(rHv, lpT, 2)
mi.c(lpT, lp)
frG = mi.obj(560, 360, "spigot 1")
mi.c(rHv, frG, 0)
frT = mi.obj(560, 390, "t b a")                      # a frame that got through goes out first, then the gate closes 500 ms
mi.c(frG, frT)
frL = mi.obj(560, 420, "list prepend sendtyped /oled/gFrame")
mi.c(frT, frL, 1)
mi.c(frL, lp)
frC = mi.obj(660, 420, "t b b")
mi.c(frT, frC, 0)
fr0 = mi.msg(760, 450, "0")
fr1 = mi.msg(660, 480, "1")
frD = mi.obj(660, 450, "delay 200")                 # 5 frames a second (apply_mirrorvis5.py)
mi.c(frC, fr0, 1); mi.c(fr0, frG, 0, 1)
mi.c(frC, frD, 0); mi.c(frD, fr1); mi.c(fr1, frG, 0, 1)
# the scope that follows a frame which went out goes out too (apply_mirrorscope.py)
wvG = mi.obj(800, 360, "spigot 0")
wv1 = mi.msg(800, 420, "1")
mi.c(frC, wv1, 0); mi.c(wv1, wvG, 0, 1)
mi.c(rHv, wvG, 1)
wvT = mi.obj(800, 390, "t b a")                      # out first, then close
mi.c(wvG, wvT)
wvL = mi.obj(800, 450, "list prepend sendtyped /oled/gWaveform")
mi.c(wvT, wvL, 1); mi.c(wvL, lp)
wv0 = mi.msg(900, 420, "0")
mi.c(wvT, wv0, 0); mi.c(wv0, wvG, 0, 1)

mi.c(lp, lt)
lpl = mi.obj(500, 390, "list prepend send /led")
mi.c(mi.obj(500, 360, "r led"), lpl)
mi.c(lpl, lt)
mi.c(lt, ok)
# controls + page state for the virtual Organelle in oled-sim.py (apply_mirrorkeys.py)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from inrelay import relay_inputs
relay_inputs(mi.obj, mi.msg, mi.c, lt, 900, 300, resend=dl)
# one packet per burst: commands go into a text buffer, sent 3 ms later in a later tick (apply_mirrortext.py)
tdef = mi.obj(450, 520, "text define mirq")
bR = mi.obj(300, 520, "route send")                 # the command without "send"
mi.c(ok, bR)
bT = mi.obj(300, 550, "t b a")                      # store first, then (re)arm the flush
mi.c(bR, bT)
ins = mi.obj(400, 580, "text insert mirq 1e+06")
toL = mi.obj(400, 555, "list")                     # "/oled/... args" as a list for [text insert]
mi.c(bT, toL, 1); mi.c(toL, ins)
fl = mi.obj(300, 580, "delay 3")
mi.c(bT, fl, 0)
flT = mi.obj(300, 610, "t b b")                     # send the buffer, then empty it
mi.c(fl, flT)
tl = mi.obj(300, 640, "text tolist mirq")
mi.c(flT, tl, 1)
clr = mi.msg(450, 640, "clear")
mi.c(flT, clr, 0); mi.c(clr, tdef)
bS = mi.obj(300, 670, "list prepend send")
bL = mi.obj(300, 700, "list trim")
mi.c(tl, bS); mi.c(bS, bL)
mi.c(bL, ns)
mi.save("mirror.pd")
