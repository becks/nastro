# exec'd from gen.py: builds seq.pd (SEQ mode: TEMPO page / STEP page, 16-step sequencer)
# The sequencer is clocked by the tape (tick16 = 16th-note index from tape.pd), so it runs
# with tape play, stays aligned with loops and can be recorded to tape.

def osc6(path, types, args):
    return f"\\; oscOut sendtyped /oled/{path} {types} 3 {args}"


NOTE_NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]

q = Patch(1500, 1200)
q.text(20, 5, "seq: AUX+E again = TEMPO / STEP page. STEP: a key writes the step under the cursor and advances")
q.text(20, 25, "AUX+A# rest - AUX+B clear (STEP page) - AUX+C5 seq on/off - AUX+A saves with the tape")
q.text(20, 45, "knobs (STEP): 1 cursor / 2 length / 3 gate / 4 swing. seqp: 0 length 1 gate 2 swing 3 on")
q.obj(20, 70, "table seqn 16")
q.obj(140, 70, "table seqp 4")
lb = q.obj(20, 100, "loadbang")
lbT = q.obj(20, 130, "t b b b b")
q.c(lb, lbT)
init = q.msg(300, 130, "\\; seqn const 0 \\; seqp 0 16 0.5 0 0")
q.c(lbT, init, 3)
# project save / load
psv = q.obj(500, 100, "t f f")
q.c(q.obj(500, 70, "r nst-save"), psv)
mkn = q.obj(500, 130, "makefilename p%d-seqn.txt"); mkp = q.obj(650, 130, "makefilename p%d-seqp.txt")
q.c(psv, mkn, 1); q.c(psv, mkp, 0)
q.c(mkn, q.msg(500, 160, "\\; seqn write \\$1")); q.c(mkp, q.msg(650, 160, "\\; seqp write \\$1"))
pld = q.obj(800, 100, "t f f b")
q.c(q.obj(800, 70, "r nst-load"), pld)
q.c(pld, init, 2)
lkn = q.obj(800, 130, "makefilename p%d-seqn.txt"); lkp = q.obj(950, 130, "makefilename p%d-seqp.txt")
q.c(pld, lkn, 1); q.c(pld, lkp, 0)
q.c(lkn, q.msg(800, 160, "\\; seqn read \\$1 \\; seq-cur 0")); q.c(lkp, q.msg(950, 160, "\\; seqp read \\$1"))
dirty = q.msg(1200, 100, "1")

# ------------------------------------------------ page toggle (AUX+E while already in SEQ)
rmode = q.obj(20, 180, "r mode")
mT = q.obj(20, 210, "t f f f")
again = q.obj(20, 240, "expr $f1==4 && $f2==4")
prevInit = q.msg(150, 210, "-1")
q.c(rmode, mT); q.c(mT, again, 2); q.c(mT, again, 1, 1)
q.c(lbT, prevInit, 2); q.c(prevInit, again, 0, 1)
agS = q.obj(20, 270, "sel 1")
pgF = q.obj(20, 300, "f")
pgN = q.obj(20, 330, "expr ($f1+1)%4")              # TEMPO -> STEP -> TOMBOLA
pgT = q.obj(20, 360, "t f f f f f")
q.c(again, agS); q.c(agS, pgF); q.c(pgF, pgN); q.c(pgN, pgT); q.c(pgT, pgF, 4, 1)
q.c(pgT, q.obj(20, 390, "s seq-page"), 0)
pg0 = q.msg(150, 330, "0")
q.c(lbT, pg0, 1); q.c(pg0, pgT)

# step page active = mode 4 and page 1 ; entry also needs AUX up
stE = q.obj(300, 420, "expr $f1==4 && $f2==1")
q.c(mT, stE, 0)
pgB = q.obj(400, 390, "t b f")
q.c(pgT, pgB, 3); q.c(pgB, stE, 1, 1); q.c(pgB, stE, 0, 0)
stT = q.obj(300, 450, "t f f f")
q.c(stE, stT)
entE = q.obj(300, 510, "expr $f1 && $f2==0")
rauxB = q.obj(450, 480, "t b f")
q.c(q.obj(450, 450, "r aux"), rauxB); q.c(rauxB, entE, 1, 1); q.c(rauxB, entE, 0, 0)
q.c(stT, entE, 2)

# keep the cursor knob "picked" (it is a selector, not a value to protect)
pkd = q.obj(600, 450, "sel 1")
pkdl = q.obj(600, 480, "delay 1")
pkm = q.msg(600, 510, "\\; pkpick 36 1")
q.c(stT, pkd, 1); q.c(pkd, pkdl); q.c(pkdl, pkm)
q.c(pkd, dirty)          # entering the STEP page redraws it

# ------------------------------------------------ knobs: page 0 -> TEMPO, page 1 -> step params
rk = q.obj(300, 180, "r seq-knob")
lp = q.obj(300, 210, "list prepend 0")
rp = q.obj(300, 240, "route 0 1 2 3")
q.c(rk, lp); q.c(lp, rp); q.c(pgT, lp, 2, 1)
q.c(rp, q.obj(300, 270, "s tempo-knob"), 0)
q.c(rp, q.obj(380, 270, "s tomb-knob"), 2)
q.c(rp, q.obj(460, 270, "s endl-knob"), 3)
rs = q.obj(450, 270, "route 1 2 3 4")
q.c(q.obj(560, 240, "r seq-step-set"), rs)
q.c(rp, rs, 1)
curE = q.obj(450, 300, "expr int($f1*15.99)")
sCur = q.msg(450, 330, "\\; seq-cur \\$1")
q.c(rs, curE, 0); q.c(curE, sCur)
for i, (ex, idx) in enumerate((("expr int(1+$f1*15.99)", 0), ("expr 0.1+$f1*0.85", 1), ("expr $f1*0.5", 2))):
    e = q.obj(560 + i * 130, 300, ex)
    m = q.msg(560 + i * 130, 330, f"\\; seqp {idx} \\$1")
    q.c(rs, e, i + 1); q.c(e, m); q.c(m, dirty)

# cursor value, shared through [r seq-cur]
rcur = q.obj(900, 180, "r seq-cur")
q.c(rcur, dirty)
curA = q.obj(900, 600, "f")      # for writing
curB = q.obj(1000, 600, "f")     # for advancing
curD = q.obj(1100, 600, "f")     # for drawing
for c in (curA, curB, curD):
    q.c(rcur, c, 0, 1)

# ------------------------------------------------ step entry (keys) and AUX keys
rn = q.obj(900, 240, "r notes")
nu = q.obj(900, 270, "unpack f f")
non = q.obj(980, 300, "> 0")
nsp = q.obj(900, 330, "spigot")
nsp2 = q.obj(900, 360, "spigot")
q.c(rn, nu); q.c(nu, non, 1); q.c(non, nsp, 0, 1); q.c(nu, nsp, 0); q.c(nsp, nsp2)
q.c(entE, nsp2, 0, 1)
# entry: note -> [seqn cursor note] ; then cursor = (cursor+1) % length ; seq on
entT = q.obj(900, 420, "t b b f")
wP = q.obj(900, 630, "pack f f")
wM = q.msg(900, 660, "\\; seqn \\$1 \\$2")
q.c(nsp2, entT)
q.c(entT, wP, 2, 1); q.c(entT, curA, 1); q.c(curA, wP); q.c(wP, wM); q.c(wM, dirty)
advE = q.obj(1000, 630, "expr ($f1+1)%max(1 \\, seqp[0])")
advM = q.msg(1000, 660, "\\; seq-cur \\$1 \\; seqp 3 1 \\; pkpick 36 1")
q.c(entT, curB, 0); q.c(curB, advE); q.c(advE, advM)

rak = q.obj(1200, 240, "r aux-key")
aks = q.obj(1200, 270, "sel 70 71 72 69")
q.c(rak, aks)
restSp = q.obj(1200, 300, "spigot")
clrSp = q.obj(1280, 300, "spigot")
q.c(stT, restSp, 0, 1); q.c(stT, clrSp, 0, 1)
q.c(aks, restSp, 0); q.c(aks, clrSp, 1)
rest0 = q.msg(1200, 330, "0")
q.c(restSp, rest0); q.c(rest0, entT)
clrM = q.msg(1280, 330, "\\; seqn const 0 \\; seq-cur 0")
q.c(clrSp, clrM); q.c(clrM, dirty)
onE = q.obj(1360, 300, "expr seqp[3]==0")
onM = q.msg(1360, 330, "\\; seqp 3 \\$1")
q.c(aks, onE, 2); q.c(onE, onM); q.c(onM, dirty)


# ------------------------------------------------ playback, clocked by the tape
rt16 = q.obj(20, 600, "r tick16")
stepE = q.obj(20, 630, "expr fmod(fmod($f1 \\, max(1 \\, seqp[0]))+max(1 \\, seqp[0]) \\, max(1 \\, seqp[0]))")
q.c(rt16, stepE)
stepT = q.obj(20, 660, "t f f")
q.c(stepE, stepT)
q.c(stepT, q.obj(120, 690, "s seq-step"), 1)
rbm = q.obj(250, 600, "r tempo-beatms")
d4 = q.obj(250, 630, "/ 4")
q.c(rbm, d4)
plE = q.obj(20, 720,
            "expr seqn[$f1]*(seqp[3]>0) \\; if($f1%2 \\, seqp[2]*$f2 \\, 0) \\; "
            "if($f1%2 \\, seqp[2]*$f2 \\, 0)+seqp[1]*$f2")
q.c(d4, plE, 0, 1); q.c(stepT, plE, 0)
plU = q.obj(20, 750, "pack f f f")
for o in range(3):
    q.c(plE, plU, o, o)
plUn = q.obj(20, 780, "unpack f f f")
q.c(plU, plUn)
onPk = q.obj(20, 840, "pack f 100 f")
offPk = q.obj(200, 840, "pack f 0 f")
q.c(plUn, offPk, 2, 2); q.c(plUn, onPk, 1, 2)
hasN = q.obj(20, 810, "moses 1")
nT = q.obj(60, 810 + 15, "t f f")
q.c(plUn, hasN, 0); q.c(hasN, nT, 1); q.c(nT, offPk, 1, 0); q.c(nT, onPk, 0, 0)
for pk, x in ((onPk, 20), (offPk, 200)):
    pp = q.obj(x, 870, "pipe f f 0")
    pr = q.obj(x, 900, "pack f f")
    q.c(pk, pp); q.c(pp, pr, 1, 1); q.c(pp, pr, 0, 0)
    q.c(pr, q.obj(x, 930, "s seq-notes"))

# ------------------------------------------------ screen (STEP page), redraw when dirty
sstT = q.obj(1200, 70 - 30, "r seq-step")
sstB = q.obj(1200, 70, "t b")
sstE = q.obj(1250, 70, "expr seqp[3]")
sstS = q.obj(1300, 70, "sel 1")
q.c(sstT, sstB); q.c(sstB, sstE); q.c(sstE, sstS); q.c(sstS, dirty)
q.c(q.obj(1300, 70, "r nst-redraw"), dirty)
q.c(q.obj(1400, 70, "r tp-play"), dirty)
fD = q.obj(600, 700, "f 1")
q.c(dirty, fD, 0, 1)
mtr = q.obj(600, 670, "metro 100")
q.c(stT, mtr, 0)
q.c(mtr, fD)
dS = q.obj(600, 730, "sel 1")
dT = q.obj(600, 760, "t b b b b b b b")
z = q.msg(750, 730, "0")
q.c(fD, dS); q.c(dS, dT); q.c(dT, z, 6); q.c(z, fD, 0, 1)
head = q.msg(600, 800, osc6("gShowInfoBar", "ii", "0") + " " + osc6("gClear", "ii", "1") + " " +
             osc6("gPrintln", "iiiiis", "1 1 8 1 SEQ") + " " + osc6("gLine", "iiiiii", "0 52 127 52 1"))
q.c(dT, head, 5)
# on/off
onB = q.obj(750, 800, "t b")
onX = q.obj(750, 830, "expr seqp[3]")
onS = q.obj(750, 860, "sel 0 1")
q.c(dT, onB, 4); q.c(onB, onX); q.c(onX, onS)
q.c(onS, q.msg(750, 890, osc6("gPrintln", "iiiiis", "24 1 8 1 off")), 0)
q.c(onS, q.msg(850, 890, osc6("gFillArea", "iiiiii", "22 0 15 10 1") + " " + osc6("gPrintln", "iiiiis", "24 1 8 0 on")), 1)
# grid: 16 steps
gT = q.obj(600, 950, "t b b")
q.c(dT, gT, 3)
g16 = q.msg(600, 980, "16"); gz = q.msg(650, 980, "0")
gu = q.obj(600, 1010, "until"); gc = q.obj(600, 1040, "f"); gc1 = q.obj(650, 1040, "+ 1")
q.c(gT, gz, 1); q.c(gz, gc, 0, 1); q.c(gT, g16, 0); q.c(g16, gu); q.c(gu, gc); q.c(gc, gc1); q.c(gc1, gc, 0, 1)
gE = q.obj(600, 1070, "expr if($f1>=seqp[0] \\, 2 \\, if(seqn[$f1]>0 \\, 0 \\, 1)) \\; 1+$f1*8 \\; "
                      "max(11 \\, min(41 \\, 41-int((seqn[$f1]-60)*1.25)))")
q.c(gc, gE)
gP = q.obj(600, 1100, "pack f f f")
for o in range(3):
    q.c(gE, gP, o, o)
gR = q.obj(600, 1130, "route 0 1")
q.c(gP, gR)
q.c(gR, q.msg(600, 1160, osc6("gFillArea", "iiiiii", "\\$1 \\$2 6 3 1")), 0)
# rest: dotted baseline (x .. x+5 at y 43)
gRest = q.obj(800, 1160, "unpack f f")
gRp = q.obj(800, 1190, "t f f")
gRe = q.obj(900, 1190, "+ 5")
gRk = q.obj(800, 1220, "pack f f")
q.c(gR, gRest, 1); q.c(gRest, gRp, 0); q.c(gRp, gRe, 1); q.c(gRe, gRk, 0, 1); q.c(gRp, gRk, 0, 0)
q.c(gRk, q.msg(800, 1250, osc6("gLine", "iiiiii", "\\$1 43 \\$2 43 1")))
# cursor column (inverted) and playhead
cB = q.obj(1000, 950, "t b")
q.c(dT, cB, 2); q.c(cB, curD)
cX = q.obj(1000, 1010, "* 8")
q.c(curD, cX)
q.c(cX, q.msg(1000, 1040, osc6("gInvertArea", "iiiii", "\\$1 10 8 36")))
phB = q.obj(1150, 950, "t b b")
q.c(dT, phB, 1)
fPl = q.obj(1150, 980, "f")
q.c(q.obj(1250, 950, "r tp-play"), fPl, 0, 1)
fSt = q.obj(1250, 1010, "f")
q.c(q.obj(1350, 980, "r seq-step"), fSt, 0, 1)
phS = q.obj(1150, 1010, "expr $f1 && seqp[3]")
phSel = q.obj(1150, 1040, "sel 1")
q.c(phB, fPl, 1); q.c(fPl, phS); q.c(phS, phSel); q.c(phSel, fSt)
phX = q.obj(1250, 1040, "expr 1+$f1*8")
q.c(fSt, phX)
q.c(phX, q.msg(1250, 1070, osc6("gFillArea", "iiiiii", "\\$1 46 6 3 1")))
# bottom: cursor step + note, length, gate, swing ; then flip
bB = q.obj(1000, 1100, "t b")
q.c(phB, bB, 0)
bE = q.obj(1000, 1130, "expr $f1+1 \\; seqp[0] \\; int(seqp[1]*100) \\; int(seqp[2]*200) \\; "
                       "seqn[$f1]>0 \\; seqn[$f1]%12 \\; int(seqn[$f1]/12)-1")
cdB = q.obj(1100, 1100, "f")
q.c(q.obj(1100, 1070, "r seq-cur"), cdB, 0, 1)
q.c(bB, cdB); q.c(cdB, bE)
bP = q.obj(1000, 1160, "pack f f f f")
for o in range(4):
    q.c(bE, bP, o, o)
q.c(bP, q.msg(1000, 1190,
              osc6("gPrintln", "iiiiisf", "1 55 8 1 S \\$1") + " " + osc6("gPrintln", "iiiiisf", "33 55 8 1 L \\$2") + " " +
              osc6("gPrintln", "iiiiisf", "65 55 8 1 G \\$3") + " " + osc6("gPrintln", "iiiiisf", "97 55 8 1 W \\$4")))
# note name of the cursor step (title, right side)
nmP = q.obj(1300, 1160, "pack f f f")
q.c(bE, nmP, 4, 0); q.c(bE, nmP, 5, 1); q.c(bE, nmP, 6, 2)
nmR = q.obj(1300, 1190, "route 0 1")
q.c(nmP, nmR)
q.c(nmR, q.msg(1300, 1220, osc6("gPrintln", "iiiiis", "70 1 8 1 rest")), 0)
nmU = q.obj(1400, 1220, "unpack f f")
q.c(nmR, nmU, 1)
nmS = q.obj(1400, 1250, "sel " + " ".join(str(i) for i in range(12)))
q.c(nmU, nmS, 0)
nmPk = q.obj(1400, 1310, "pack s f")
for i, nm in enumerate(NOTE_NAMES):
    m = q.msg(1400 + (i % 6) * 60, 1280 + (i // 6) * 20, f"symbol {nm}")
    q.c(nmS, m, i); q.c(m, nmPk)
q.c(nmU, nmPk, 1, 1)
q.c(nmPk, q.msg(1400, 1340, osc6("gPrintln", "iiiiisf", "70 1 8 1 \\$1 \\$2")))
flip = q.msg(600, 1250, "\\; oscOut sendtyped /oled/gFlip i 3")
q.c(dT, flip, 0)
# wire the project file names (created above) to write / read messages
q.save("seq.pd")
