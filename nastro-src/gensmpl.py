def searcher(x, raw_outlet, send):
    """raw index in -> first upward zero crossing within W samples (or raw) -> [s send]"""
    inT = r.obj(x, 830, "t b b b f")
    base = r.obj(x + 120, 860, "f")
    r.c(rawE, inT, raw_outlet)
    r.c(inT, base, 3, 1)
    found = r.obj(x + 200, 860, "f -1")
    rf = r.msg(x + 200, 830, "-1")
    i0 = r.msg(x + 280, 830, "0")
    cnt = r.obj(x, 920, "f")
    cnt1 = r.obj(x + 50, 920, "+ 1")
    r.c(inT, rf, 2); r.c(rf, found, 0, 1); r.c(inT, i0, 1); r.c(i0, cnt, 0, 1)
    chunk = r.obj(x, 860, "t b b")
    r.c(inT, chunk, 0)
    nM = r.msg(x + 60, 890, f"{CH}")
    un = r.obj(x + 60, 920 - 0, "until")
    r.c(chunk, nM, 1); r.c(nM, un); r.c(un, cnt); r.c(cnt, cnt1); r.c(cnt1, cnt, 0, 1)
    # test sample base+i
    idxE = r.obj(x, 950, "+")
    r.c(cnt, idxE)
    tE = r.obj(x, 980, "expr if($f1>=$f2-1 \\, 2 \\, if($f1>0 && smpl[max(0 \\, $f1-1)]<=0 && smpl[$f1]>0 \\, 1 \\, 0)) \; $f1")
    r.c(fLn, tE, 0, 1)
    tP = r.obj(x, 1010, "pack f f")
    r.c(idxE, tE); r.c(tE, tP, 1, 1); r.c(tE, tP, 0, 0)
    tR = r.obj(x, 1040, "route 1 2")
    r.c(tP, tR)
    hitT = r.obj(x, 1070, "t b f")
    r.c(tR, hitT, 0); r.c(hitT, found, 1, 1); r.c(hitT, un, 0, 1)        # found: remember, stop
    endT = r.obj(x + 80, 1070, "t b b")
    m2 = r.msg(x + 160, 1100, "-2")
    r.c(tR, endT, 1); r.c(endT, m2, 1); r.c(m2, found, 0, 1); r.c(endT, un, 0, 1)   # table end: stop
    # after each chunk: done if found, hit the end, or searched W samples
    chk = r.obj(x, 1130, "t b")
    r.c(chunk, chk, 0)
    stE = r.obj(x, 1160, f"expr if($f1>=0 \\, $f1 \\, if($f1==-2 || $f2>={W} \\, $f3 \\, -1))")
    fCnt = r.obj(x + 150, 1130, "f"); fBase = r.obj(x + 200, 1130, "f")
    r.c(cnt, fCnt, 0, 1); r.c(inT, fBase, 3, 1)
    chT = r.obj(x, 1190 - 0, "t b b b")
    r.c(chk, chT); r.c(chT, fBase, 2); r.c(fBase, stE, 0, 2); r.c(chT, fCnt, 1); r.c(fCnt, stE, 0, 1)
    r.c(chT, found, 0); r.c(found, stE)
    res = r.obj(x, 1220, "moses 0")
    r.c(stE, res)
    again = r.obj(x, 1250, "delay 1")
    r.c(res, again, 0); r.c(again, chunk)
    r.c(res, r.obj(x + 80, 1250, f"s {send}"), 1)
    # base -> adder (right inlet), so idx = base + i
    r.c(inT, idxE, 3, 1)


