# exec'd from gen.py: SMPL engine voice (smpl-voice.pd) and the sample recorder (smpl.pd)
# The engine wrapper synth-smpl.pd is built by gensynth.py's generic engine() builder.
SMAX = 441000   # 10 s at 44.1 kHz

# ---------------------------------------------------------------- smpl-voice.pd
# De-click: on note-on the voice first fades out (1.5 ms), then (after 1.5 ms) jumps the
# playhead, then fades in. START/END come in as zero-crossing-snapped sample indices
# (smp-s0 / smp-s1, computed in smpl.pd).
v = Patch(900, 700)
v.text(20, 5, "smpl-voice: plays the sample between smp-s0 and smp-s1 - pitched from C4 = original")
inl = v.obj(20, 40, "inlet")
tll = v.obj(20, 70, "t l l")
upn = v.obj(250, 100, "unpack f f")
rateE = v.obj(250, 130, "expr pow(2 \\, ($f1-60)/12)")
fRate = v.obj(250, 160, "f 1")
v.c(inl, tll); v.c(tll, upn, 1); v.c(upn, rateE); v.c(rateE, fRate, 0, 1)
upv = v.obj(20, 100, "unpack f f")
mos = v.obj(20, 130, "moses 1")
v.c(tll, upv, 0); v.c(upv, mos, 1)
lb = v.obj(600, 40, "loadbang")
srt = v.obj(600, 70, "samplerate~")
v.c(lb, srt)
# onset, length, phasor frequency, one-shot hold (from the note start)
onE = v.obj(250, 220,
            "expr $f2 \; max(64 \\, $f3-$f2) \; $f1*$f4/max(64 \\, $f3-$f2) \; "
            "if($f5 \\, 1e+09 \\, max(1 \\, max(64 \\, $f3-$f2)/$f4*1000/$f1-15))+3")
v.c(v.obj(400, 130, "r smp-s0"), onE, 0, 1)
v.c(v.obj(500, 130, "r smp-s1"), onE, 0, 2)
v.c(srt, onE, 0, 3)
v.c(v.obj(600, 130, "r smp-loop"), onE, 0, 4)
onT = v.obj(20, 160, "t b")
v.c(mos, onT, 1); v.c(onT, fRate); v.c(fRate, onE)
# envelope now: fade out 1.5 ms, fade in after 3 ms, one-shot fade at the end
env = v.msg(400, 300, "0 1.5 \\, 1 3 3 \\, 0 15 \\$1")
v.c(onE, env, 3)
venv = v.obj(400, 360, "vline~")
v.c(env, venv)
# playhead jump 1.5 ms later (when the voice is silent)
pk = v.obj(250, 260, "pack f f f")
v.c(onE, pk, 2, 2); v.c(onE, pk, 1, 1); v.c(onE, pk, 0, 0)
held = v.obj(250, 290, "list")
v.c(pk, held, 0, 1)
dl = v.obj(150, 260, "delay 1.5")
v.c(onT, dl)
v.c(dl, held)
apU = v.obj(250, 320, "unpack f f f")
v.c(held, apU)
rd = v.obj(20, 460, "tabread4~ smpl")
ph = v.obj(150, 400, "phasor~")
ln = v.obj(150, 430, "*~ 0")
z = v.msg(250, 360, "0")
apT = v.obj(250, 340, "t b f")
v.c(apU, ph, 2, 0)            # frequency
v.c(apU, ln, 1, 1)            # length
v.c(apU, apT, 0); v.c(apT, rd, 1, 1); v.c(apT, z, 0); v.c(z, ph, 0, 1)   # onset, then phase 0
v.c(ph, ln); v.c(ln, rd)
# note off: release
fRel = v.obj(20, 250, "f 300")
v.c(v.obj(80, 220, "r smp-rel"), fRel, 0, 1)
offT = v.obj(20, 190, "t b")
v.c(mos, offT, 0); v.c(offT, fRel)
relM = v.msg(20, 280, "0 \\$1")
v.c(fRel, relM); v.c(relM, venv)
vca = v.obj(20, 500, "*~")
v.c(rd, vca, 0, 0); v.c(venv, vca, 0, 1)
v.c(vca, v.obj(20, 540, "outlet~"))
v.save("smpl-voice.pd")

